const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { Buffer } = require('node:buffer');

// A project-specific UUID namespace. IDs include the source revision and source table/ID.
const namespace = Buffer.from('49bcdeef66b54d7090673b7b476bf820', 'hex');
function stableId(kind, id) {
  const bytes = crypto.createHash('sha1').update(namespace).update(`carenet-v1:${kind}:${id}`).digest().subarray(0, 16);
  bytes[6] = (bytes[6] & 15) | 80;
  bytes[8] = (bytes[8] & 63) | 128;
  const h = bytes.toString('hex');
  return `${h.slice(0,8)}-${h.slice(8,12)}-${h.slice(12,16)}-${h.slice(16,20)}-${h.slice(20)}`;
}
function audit(source) {
  const rows = [];
  for (const line of source.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const match = /^insert into (region|district|township) \(id, (?:(region_id|district_id), )?name\) values \((\d+), (?:(\d+), )?'((?:[^']|'')*)'\);$/i.exec(line);
    if (!match) throw new Error(`Unrecognized source SQL: ${line}`);
    const [,kind,,id,parentId,rawName] = match;
    const name = rawName.replace(/''/g,"'").trim();
    if (!name) throw new Error('Empty geographic name');
    rows.push({kind,sourceId:Number(id),parentSourceId:parentId?Number(parentId):null,rawName:rawName.replace(/''/g,"'"),name,id:stableId(kind,id),code:`carenet-v1-${kind}-${id}`,active:true});
  }
  const keys = new Set();
  for (const row of rows) {
    const key = `${row.kind}:${row.sourceId}`;
    if (keys.has(key)) throw new Error(`Duplicate source ID ${key}`);
    keys.add(key);
  }
  for (const row of rows) {
    if (row.parentSourceId !== null && !keys.has(`${row.kind==='district'?'region':'district'}:${row.parentSourceId}`)) throw new Error(`Invalid parent for ${row.kind}:${row.sourceId}`);
  }
  const groups = new Map();
  for (const row of rows) {
    const key = `${row.kind}:${row.parentSourceId}:${row.name.toLowerCase()}`;
    groups.set(key,[...(groups.get(key)||[]),row]);
  }
  const duplicates = [...groups.values()].filter(group=>group.length>1);
  for (const group of duplicates) for (const row of group) row.active = false;
  const names = new Map();
  for (const row of rows.filter(row=>row.kind==='township')) names.set(row.name.toLowerCase(),[...(names.get(row.name.toLowerCase())||[]),row]);
  return {rows,duplicates,ambiguousNames:[...names.values()].filter(group=>new Set(group.map(row=>row.parentSourceId)).size>1),trimmed:rows.filter(row=>row.rawName!==row.name)};
}
function generate(root = path.resolve(__dirname, '..')) {
  const source = fs.readFileSync(path.join(root,'docs/data/carenet-geography-v1.sql'),'utf8');
  const result = audit(source);
  const quote = value => `'${value.replace(/'/g,"''")}'`;
  let sql = '-- Generated by scripts/geography-import.cjs; review docs/geography-import-audit.json first.\n-- CareNet source blob bd247b556f7d77d407abceea159752e1183b4a73; never execute original import.sql.\n';
  for (const kind of ['region','district','township']) {
    const table = {region:'geo_regions',district:'geo_districts',township:'geo_townships'}[kind];
    for (const row of result.rows.filter(row=>row.kind===kind)) {
      const parentKind = kind==='district'?'region':'district';
      const parent = row.parentSourceId===null?'':`, ${quote(stableId(parentKind,row.parentSourceId))}`;
      sql += `INSERT INTO public.${table}(id,code,name_en,active${row.parentSourceId===null?'':`, ${parentKind}_id`}) VALUES (${quote(row.id)},${quote(row.code)},${quote(row.name)},${row.active}${parent}) ON CONFLICT (id) DO NOTHING;\n`;
    }
  }
  // A collision must fail review/import rather than silently repurpose an existing ID.
  for (const kind of ['region','district','township']) {
    const table = {region:'geo_regions',district:'geo_districts',township:'geo_townships'}[kind];
    sql += `DO $$ BEGIN IF EXISTS (SELECT 1 FROM (VALUES\n`;
    const parentKind = kind==='district'?'region':'district';
    sql += result.rows.filter(row=>row.kind===kind).map(row=>`(${quote(row.id)}::uuid,${quote(row.code)},${quote(row.name)}${kind==='region'?'':`,${quote(stableId(parentKind,row.parentSourceId))}::uuid`})`).join(',\n');
    sql += `) AS expected(id,code,name${kind==='region'?'':',parent_id'}) JOIN public.${table} actual USING(id) WHERE actual.code <> expected.code OR actual.name_en <> expected.name${kind==='region'?'':` OR actual.${parentKind}_id <> expected.parent_id`}) THEN RAISE EXCEPTION 'Geographic seed ID collision'; END IF; END $$;\n`;
  }
  fs.writeFileSync(path.join(root,'supabase/migrations/20261116101000_seed_myanmar_geography_v1.sql'),sql);
  fs.writeFileSync(path.join(root,'docs/geography-source-mapping.json'),JSON.stringify({version:'carenet-v1',sourceBlob:'bd247b556f7d77d407abceea159752e1183b4a73',rows:result.rows},null,2)+'\n');
  fs.writeFileSync(path.join(root,'docs/geography-import-audit.json'),JSON.stringify({version:'carenet-v1',source:'https://github.com/waiyanphyo-max/CareNet_Backend/blob/main/src/main/resources/import.sql',sourceBlob:'bd247b556f7d77d407abceea159752e1183b4a73',counts:Object.fromEntries(['region','district','township'].map(kind=>[kind,result.rows.filter(row=>row.kind===kind).length])),invalidParents:[],duplicates:result.duplicates,ambiguousNames:result.ambiguousNames,whitespaceNormalized:result.trimmed.map(({kind,sourceId,rawName,name})=>({kind,sourceId,rawName,name})),reviewRequired:['Same-district duplicate records retain separate deterministic IDs but are inactive pending explicit review; no records are merged.','All administrative boundaries and transliterations are source-era, unverified reference data. Yangon four-district grouping and all other boundaries require authoritative current review before production rollout.','No missing entities or Burmese translations have been inferred. Codes identify source records, not official administrative codes.']},null,2)+'\n');
  return result;
}
if (require.main === module) { const result=generate(); console.log(`Audited ${result.rows.length} records; ${result.duplicates.length} duplicate groups; ${result.trimmed.length} whitespace repairs.`); }
module.exports={audit,stableId,generate};
